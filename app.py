def load_data():
    """
    Downloads the latest version of the Amazon Product Reviews dataset
    using kagglehub and loads the CSV file into a pandas DataFrame.
    """
    # Downloading the dataset
    path = kagglehub.dataset_download("miriamodeyianypeter/sentiment-analysis-amazon-product-reviews")
    print("Path to dataset files:", path)

    # Finding the first CSV file in the downloaded folder
    csv_files = [f for f in os.listdir(path) if f.endswith('.csv')]
    if not csv_files:
        raise FileNotFoundError("No CSV file found in the downloaded dataset folder.")
    file_path = os.path.join(path, csv_files[0])
    df = pd.read_csv(file_path)
    return df

# Loading the dataset
df = load_data()

# dataset is large, so taking a random sample (e.g., 1000 rows) for speed.
if len(df) > 1000:
    df_sample = df.sample(1000, random_state=42).reset_index(drop=True)
else:
    df_sample = df.copy()

print(f"Using {len(df_sample)} sample reviews for clustering.")

###########################################################
# 2. Text Vectorization (TF-IDF)
###########################################################

def vectorize_text(data, column='review_body'):
    """
    Vectorizes text from the specified column using TF-IDF.

    Parameters:
      - data: pandas DataFrame containing the text data.
      - column: name of the column containing text (default is 'review_body').

    Returns:
      - X: TF-IDF feature matrix.
      - vectorizer: the fitted TfidfVectorizer instance.
    """
    vectorizer = TfidfVectorizer(max_features=1000, stop_words='english')
    # Filling any missing review text with an empty string
    X = vectorizer.fit_transform(data[column].fillna(''))
    return X, vectorizer

# Vectorizing the review text
X, vectorizer = vectorize_text(df_sample, column='review_body')

###########################################################
# 3. Clustering and Dimensionality Reduction Functions
###########################################################

def perform_clustering(X, n_clusters):
    """
    Performs K-Means clustering on the provided feature matrix X.

    Parameters:
      - X: Feature matrix (TF-IDF in our case).
      - n_clusters: number of clusters to form.

    Returns:
      - labels: cluster labels for each sample.
      - kmeans: the fitted KMeans model.
    """
    kmeans = KMeans(n_clusters=n_clusters, random_state=42)
    kmeans.fit(X)
    labels = kmeans.labels_
    return labels, kmeans

def reduce_dimensionality(X, n_components=2):
    """
    Reduces the dimensionality of X to n_components using PCA.

    Parameters:
      - X: Feature matrix (sparse or dense).
      - n_components: number of dimensions for output (default is 2).

    Returns:
      - X_reduced: data transformed into n_components dimensions.
      - pca: the fitted PCA model.
    """
    # Converting the sparse matrix to dense format for PCA
    pca = PCA(n_components=n_components, random_state=42)
    X_reduced = pca.fit_transform(X.toarray())
    return X_reduced, pca

def compute_elbow_scores(X, k_range=range(2, 11)):
    """
    Computes inertia values for K-Means clustering over a range of cluster numbers.

    Parameters:
      - X: Feature matrix.
      - k_range: range of k (number of clusters) to evaluate.

    Returns:
      - ks: list of k values.
      - inertias: list of corresponding inertia values.
    """
    inertias = []
    ks = list(k_range)
    for k in ks:
        kmeans = KMeans(n_clusters=k, random_state=42)
        kmeans.fit(X)
        inertias.append(kmeans.inertia_)
    return ks, inertias

def compute_silhouette(X, labels):
    """
    Computes the silhouette score for the clustering.

    Parameters:
      - X: Feature matrix.
      - labels: cluster labels from clustering.

    Returns:
      - score: silhouette score (float).
    """
    score = silhouette_score(X, labels)
    return score

