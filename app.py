@app.callback(
    [Output('scatter-plot', 'figure'),
     Output('cluster-stats', 'children'),
     Output('elbow-plot', 'figure'),
     Output('silhouette-score', 'children')],
    [Input('cluster-slider', 'value')]
)
def update_dashboard(n_clusters):
    """
    Callback function that updates the scatter plot, cluster statistics,
    elbow plot, and silhouette score based on the selected number of clusters.
    """
    # 1. Performing clustering on the TF-IDF features
    labels, kmeans = perform_clustering(X, n_clusters)

    # 2. Reducing dimensions for 2D visualization using PCA
    X_reduced, _ = reduce_dimensionality(X, n_components=2)

    # 3. Building a DataFrame for visualization
    viz_df = pd.DataFrame(X_reduced, columns=['PC1', 'PC2'])
    viz_df['Cluster'] = labels.astype(str)

    # Creating a scatter plot with distinct colors for each cluster
    scatter_fig = px.scatter(viz_df, x='PC1', y='PC2', color='Cluster',
                             title=f"Clustering Visualization with {n_clusters} Clusters",
                             hover_data=[viz_df.index])

    # 4. Computing cluster statistics (number of points and centroid locations)
    stats_children = []
    unique_clusters = np.unique(labels)
    for cluster in unique_clusters:
        count = np.sum(labels == cluster)
        centroid = viz_df[viz_df['Cluster'] == str(cluster)][['PC1', 'PC2']].mean().round(2)
        stats_children.append(
            html.P(f"Cluster {cluster}: {count} points, Centroid (PC1, PC2): ({centroid['PC1']}, {centroid['PC2']})")
        )

    # 5. Computing the Elbow Method plot (inertia vs. number of clusters)
    ks, inertias = compute_elbow_scores(X, k_range=range(2, 11))
    elbow_fig = px.line(x=ks, y=inertias, markers=True,
                        title="Elbow Method: Inertia vs. Number of Clusters",
                        labels={'x': 'Number of Clusters', 'y': 'Inertia'})

    # 6. Computing and displaying the silhouette score for the current clustering
    try:
        sil_score = compute_silhouette(X, labels)
        sil_score_text = f"Silhouette Score for {n_clusters} clusters: {sil_score:.3f}"
    except Exception as e:
        sil_score_text = f"Error computing silhouette score: {str(e)}"

    return scatter_fig, stats_children, elbow_fig, sil_score_text

